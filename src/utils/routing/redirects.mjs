/**
 * The adapter writes redirect rules that only match `/old`, but every URL in our
 * sitemap, and so most of what's indexed, is `/old/`. Runs after the adapter's own
 * build step and lets those rules match both.
 */
export function matchTrailingSlashOnRedirects(adapter) {
  const adapterBuildDone = adapter.hooks['astro:build:done'];
  adapter.hooks['astro:build:done'] = async (options) => {
    await adapterBuildDone(options);
    const configPath = `${process.cwd()}/.vercel/output/config.json`;
    const config = JSON.parse(readFileSync(configPath, 'utf8'));
    const sources = new Set(Object.keys(redirects).map((source) => `^${source}$`));
    for (const route of config.routes) {
      if (sources.has(route.src)) route.src = route.src.replace(/\$$/, '/?$');
    }
    writeFileSync(configPath, JSON.stringify(config, null, '\t'));
  };
  return adapter;
}
